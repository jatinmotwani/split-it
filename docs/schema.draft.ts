/**
 * Drizzle schema DRAFT for review (kickoff, 2026-09-28).
 *
 * Not compiled by the app. In Phase 1 (task 1.7) the Phase 0–1 sections move
 * into src/server/db/schema/*.ts. Later sections move in with their phase, so
 * each phase's migration only adds its own tables.
 *
 * Conventions
 * - Our ids are uuid, generated in the app (UUIDv7, often on the client).
 * - Better Auth ids are text; FKs to `user.id` are therefore text.
 * - Money is bigint minor units, read as JS number (assertMinor at boundaries).
 * - All timestamps are timestamptz.
 */
import { sql } from 'drizzle-orm';
import {
  bigint,
  boolean,
  char,
  check,
  date,
  index,
  integer,
  jsonb,
  numeric,
  pgEnum,
  pgTable,
  primaryKey,
  smallint,
  text,
  timestamp,
  uniqueIndex,
  uuid,
  varchar,
} from 'drizzle-orm/pg-core';

// Shared column helpers ------------------------------------------------------

const money = (name: string) => bigint(name, { mode: 'number' });
const currency = (name: string) => char(name, { length: 3 });
const createdAt = () => timestamp('created_at', { withTimezone: true }).notNull().defaultNow();
const updatedAt = () => timestamp('updated_at', { withTimezone: true }).notNull().defaultNow();
const tstz = (name: string) => timestamp(name, { withTimezone: true });

// Types owned by src/lib/money and src/lib/contracts (placeholders here) -----

type SplitInput = { type: string } & Record<string, unknown>;
type EntrySnapshot = Record<string, unknown>;
type ActivityData = Record<string, unknown>;

// ============================================================================
// Phase 0 — Better Auth (generated by `@better-auth/cli generate`; shown so
// FKs type-check). session / account / verification are generated alongside.
// ============================================================================

export const user = pgTable('user', {
  id: text('id').primaryKey(),
  name: text('name').notNull(),
  email: text('email').notNull().unique(),
  emailVerified: boolean('email_verified').notNull().default(false),
  image: text('image'),
  isAnonymous: boolean('is_anonymous').notNull().default(false), // anonymous plugin
  createdAt: createdAt(),
  updatedAt: updatedAt(),
});

