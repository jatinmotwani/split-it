export const groupType = pgEnum('group_type', ['trip', 'home', 'couple', 'other', 'direct']);
export const memberRole = pgEnum('member_role', ['owner', 'member']);
export const entryKind = pgEnum('entry_kind', ['expense', 'settlement', 'opening_balance']);
export const splitType = pgEnum('split_type', [
  'equal',
  'exact',
  'percentage',
  'shares',
  'adjustment',
  'itemized',
  'imported_net',
]);
export const entrySource = pgEnum('entry_source', ['app', 'splitwise_import', 'recurring']);
export const settlementMethod = pgEnum('settlement_method', ['cash', 'upi', 'bank', 'other']);
export const revisionReason = pgEnum('revision_reason', ['edit', 'delete', 'restore', 'conflict']);

export const groups = pgTable(
  'groups',
  {
    id: uuid('id').primaryKey(),
    name: varchar('name', { length: 60 }).notNull(),
    type: groupType('type').notNull().default('other'),
    defaultCurrency: currency('default_currency').notNull().default('INR'),
    simplifyDebts: boolean('simplify_debts').notNull().default(true),
    inviteCode: text('invite_code').notNull(), // 128-bit random, base64url; rotatable
    inviteExpiresAt: tstz('invite_expires_at'),
    // type = 'direct' only: sorted "userA:userB" once both members are real users
    directKey: text('direct_key'),
    createdByUserId: text('created_by_user_id').references(() => user.id, { onDelete: 'set null' }),
    lastActivityAt: tstz('last_activity_at').notNull().defaultNow(),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (t) => [
    uniqueIndex('groups_invite_code_uq').on(t.inviteCode),
    uniqueIndex('groups_direct_key_uq').on(t.directKey).where(sql`${t.directKey} IS NOT NULL`),
    check('groups_currency_ck', sql`${t.defaultCurrency} ~ '^[A-Z]{3}$'`),
  ],
);

export const groupMembers = pgTable(
  'group_members',
  {
    id: uuid('id').primaryKey(),
    groupId: uuid('group_id')
      .notNull()
      .references(() => groups.id, { onDelete: 'cascade' }),
    // null = placeholder ("Ravi — not joined yet"); anonymous user = guest
    userId: text('user_id').references(() => user.id, { onDelete: 'set null' }),
    displayName: varchar('display_name', { length: 40 }).notNull(),
    role: memberRole('role').notNull().default('member'),
    claimTokenHash: text('claim_token_hash'), // sha256 of a single-use token
    claimTokenExpiresAt: tstz('claim_token_expires_at'),
    joinedAt: tstz('joined_at'), // null until someone joins/claims this spot
    removedAt: tstz('removed_at'), // soft remove; only at zero balance
    createdAt: createdAt(),
  },
  (t) => [
    index('group_members_group_idx').on(t.groupId),
    index('group_members_user_idx').on(t.userId),
    uniqueIndex('group_members_active_user_uq')
      .on(t.groupId, t.userId)
      .where(sql`${t.userId} IS NOT NULL AND ${t.removedAt} IS NULL`),
    uniqueIndex('group_members_claim_token_uq')
      .on(t.claimTokenHash)
      .where(sql`${t.claimTokenHash} IS NOT NULL`),
  ],
);

export const entries = pgTable(
  'entries',
  {
    id: uuid('id').primaryKey(), // client-generated UUIDv7; also the rounding seed
    groupId: uuid('group_id')
      .notNull()
      .references(() => groups.id, { onDelete: 'cascade' }),
    kind: entryKind('kind').notNull(),
    description: varchar('description', { length: 120 }).notNull(),
    category: varchar('category', { length: 32 }), // key from src/lib/categories
    amount: money('amount').notNull(),
    currency: currency('currency').notNull(),
    // Phase 3: set only when a user explicitly converts an expense
    originalAmount: money('original_amount'),
    originalCurrency: currency('original_currency'),
    fxRate: numeric('fx_rate', { precision: 20, scale: 10 }),
    fxDate: date('fx_date'),
    fxSource: text('fx_source'),
    date: date('date').notNull(), // calendar date as the user sees it
    notes: varchar('notes', { length: 1000 }),
    splitType: splitType('split_type').notNull(),
    splitInput: jsonb('split_input').$type<SplitInput>().notNull(), // canonical, versioned input
    settlementMethod: settlementMethod('settlement_method'), // kind = 'settlement' only
    createdByMemberId: uuid('created_by_member_id')
      .notNull()
      .references(() => groupMembers.id),
    updatedByMemberId: uuid('updated_by_member_id').references(() => groupMembers.id),
    source: entrySource('source').notNull().default('app'),
    importId: uuid('import_id'), // FK to imports added in Phase 2
    importRowHash: text('import_row_hash'),
    recurringRuleId: uuid('recurring_rule_id'), // FK to recurring_rules added in Phase 3
    recurringPeriod: text('recurring_period'), // e.g. '2026-10'
    version: integer('version').notNull().default(1),
    deletedAt: tstz('deleted_at'),
    deletedByMemberId: uuid('deleted_by_member_id').references(() => groupMembers.id),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (t) => [
    index('entries_group_live_date_idx').on(t.groupId, t.deletedAt, t.date.desc()),
    index('entries_group_creator_idx').on(t.groupId, t.createdByMemberId, t.createdAt.desc()),
    uniqueIndex('entries_import_row_uq')
      .on(t.groupId, t.importRowHash)
      .where(sql`${t.importRowHash} IS NOT NULL`),
    uniqueIndex('entries_recurring_period_uq')
      .on(t.recurringRuleId, t.recurringPeriod)
      .where(sql`${t.recurringRuleId} IS NOT NULL`),
    check('entries_amount_ck', sql`${t.amount} >= 0`),
    check('entries_currency_ck', sql`${t.currency} ~ '^[A-Z]{3}$'`),
    check(
      'entries_settlement_method_ck',
      sql`(${t.kind} = 'settlement') OR (${t.settlementMethod} IS NULL)`,
    ),
  ],
);

